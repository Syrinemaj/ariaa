"""
Canonicalizes the raw business_domain list before it's shown to the intent
analyzer (app/planner/service.py::_get_known_domains).

Why this exists: business_domain is free-text output from an earlier,
per-endpoint AI classification pass (noise_scoring.py, endpoint_understanding.py)
with no controlled vocabulary — on one real HAR this produced 33 distinct
strings for what a human would call a handful of real domains ("hr" /
"HR Analytics" / "hr_system" / "human_resources" / "Human Resources" /
"human_resources_analytics"...). Traced end to end: feeding that raw list
to the intent analyzer as grounding made it settle on the abbreviated
variant ("hr") instead of the dominant one ("human_resources"), which then
made the downstream plan-selection LLM call reject the correct endpoint
4/4 times in testing, even though it was correctly retrieved by RAG every
time — i.e. this was silently breaking real plan generation, not a cosmetic
issue.

Not fixed with string heuristics (lowercase/underscore normalization only
merges exact-casing duplicates — "hr" and "human_resources" share no
characters positionally, so no string-similarity technique catches that
without a hardcoded synonym dictionary). An LLM call reasoning about the
actual list — same approach already proven for endpoint grouping
(app/ai/endpoint_grouping.py) — handles the abbreviation/synonym problem
directly. Cached per run (the domain list is stable once ingestion is
done), so this costs one LLM call per run, not per plan-generation request.
"""
from __future__ import annotations

from typing import Any, Dict, List

SYSTEM_PROMPT = """You receive a list of business-domain labels, auto-generated by an earlier AI
classification pass over the same dataset with no controlled vocabulary —
it commonly produces several near-duplicate labels for the same real
domain: different casing ("HR" / "hr"), abbreviations ("hr" for
"human_resources"), and added qualifiers ("human_resources_analytics",
"hr_system") that are really the same core domain.

Merge obvious near-duplicates/synonyms/abbreviations into ONE canonical
label each — prefer the clearest, most complete snake_case form (e.g.
"human_resources" over "hr" or "HR"). Keep genuinely distinct domains
separate (e.g. "localization" and "monitoring" are not the same domain
just because both are short/technical).

Return strict JSON only, matching the schema exactly.
"""

DOMAIN_CANONICALIZATION_SCHEMA: Dict[str, Any] = {
    "name": "domain_canonicalization",
    "strict": True,
    "schema": {
        "type": "object",
        "properties": {
            "canonical_domains": {"type": "array", "items": {"type": "string"}},
        },
        "required": ["canonical_domains"],
        "additionalProperties": False,
    },
}


def build_canonicalization_payload(raw_domains: List[str]) -> Dict[str, Any]:
    return {"raw_domains": raw_domains}
